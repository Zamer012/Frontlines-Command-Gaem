export const getQuestForUnit = (unitCode: string): TacticalQuest | undefined => {
  return TACTICAL_QUESTS.find((q) => q.rewardUnitCode === unitCode);
};

export const getQuestProgressInfo = (
  quest: TacticalQuest,
  progressObj: Record<string, number> = {}
) => {
  const current = Math.min(quest.targetCount, progressObj[quest.statKey] || 0);
  const target = quest.targetCount;
  const percentage = Math.min(100, Math.round((current / target) * 100));
  const completed = current >= target;
  return { current, target, percentage, completed };
};
